#!/bin/bash

echo "========================================"
echo "双摄像头标定程序"
echo "========================================"
echo ""
echo "请确保:"
echo "1. 两个USB摄像头已连接"
echo "2. 标定板已准备 (9x6棋盘格)"
echo "3. 摄像头视野有足够重叠"
echo ""
read -p "按回车键开始标定..."

python3 camera_calibrator.py

if [ -f "calibration.json" ]; then
    echo ""
    echo "========================================"
    echo "标定完成!"
    echo "标定参数已保存到 calibration.json"
    echo "========================================"
else
    echo ""
    echo "========================================"
    echo "标定失败，请检查摄像头连接和标定板"
    echo "========================================"
fi

read -p "按回车键退出..."